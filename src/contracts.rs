const CONTRACT_OWNER: &str = "rust:microck_pangram_cli::contracts";
const DRAFT_2020_12: &str = "https://json-schema.org/draft/2020-12/schema";

/// One path and its canonical generated bytes, relative to the repository root.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedArtifact {
    pub path: String,
    pub bytes: Vec<u8>,
}

/// Contract generation failed before every artifact could be produced.
#[derive(Debug, Error)]
pub enum ContractGenerationError {
    #[error("failed to serialize a generated contract: {0}")]
    Serialize(#[from] serde_json::Error),
    #[error("failed to write generated contract {path}: {source}")]
    Write {
        path: String,
        #[source]
        source: std::io::Error,
    },
}

/// Produces every committed contract without consulting the committed output.
pub fn generated_artifacts() -> Result<Vec<GeneratedArtifact>, ContractGenerationError> {
    let mut help_command = runtime_command();
    let help = format!("{}\n", help_command.render_help().to_string().trim_end());

    Ok(vec![
        json_artifact("contracts/config.schema.json", config_schema())?,
        json_artifact(
            "contracts/install-receipt.schema.json",
            install_receipt_schema(),
        )?,
        json_artifact(
            "contracts/manifest-signature.schema.json",
            manifest_signature_schema(),
        )?,
        json_artifact("contracts/output.schema.json", output_schema())?,
        json_artifact("contracts/tui-state.schema.json", tui_state_schema())?,
        json_artifact(
            "contracts/update-manifest.schema.json",
            update_manifest_schema(),
        )?,
        json_artifact("contracts/update-state.schema.json", update_state_schema())?,
        GeneratedArtifact {
            path: "generated/cli-help.txt".into(),
            bytes: help.into_bytes(),
        },
        compact_json_artifact("generated/cli-reference.json", cli_reference())?,
        json_artifact("generated/error-reference.json", error_reference())?,
    ])
}

/// Writes the canonical artifacts below `root`.
pub fn write_generated_artifacts(root: &Path) -> Result<(), ContractGenerationError> {
    let artifacts = generated_artifacts()?;
    let nonce = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_nanos();
    let mut staged: Vec<(PathBuf, PathBuf)> = Vec::with_capacity(artifacts.len());

    // Complete every fallible content write before replacing any committed
    // artifact. Cross-directory replacement cannot be one atomic operation,
    // but ordinary staging failures leave the previous set intact.
    for (index, artifact) in artifacts.iter().enumerate() {
        let path = root.join(&artifact.path);
        let parent = path.parent().expect("generated artifacts have a parent");
        let file_name = path
            .file_name()
            .and_then(|name| name.to_str())
            .expect("generated artifact names are UTF-8");
        let temporary = parent.join(format!(
            ".{file_name}.{}-{nonce}-{index}.tmp",
            std::process::id()
        ));
        let stage_result = (|| -> std::io::Result<()> {
            fs::create_dir_all(parent)?;
            let mut file = fs::OpenOptions::new()
                .write(true)
                .create_new(true)
                .open(&temporary)?;
            file.write_all(&artifact.bytes)?;
            file.sync_all()
        })();

        if let Err(source) = stage_result {
            cleanup_staged(&staged);
            let _ = fs::remove_file(&temporary);
            return Err(ContractGenerationError::Write {
                path: path.display().to_string(),
                source,
            });
        }
        staged.push((temporary, path));
    }

    for index in 0..staged.len() {
        let (temporary, path) = &staged[index];
        if let Err(source) = fs::rename(temporary, path) {
            cleanup_staged(&staged[index..]);
            return Err(ContractGenerationError::Write {
                path: path.display().to_string(),
                source,
            });
        }
    }
    Ok(())
}

fn cleanup_staged(staged: &[(PathBuf, PathBuf)]) {
    for (temporary, _) in staged {
        let _ = fs::remove_file(temporary);
    }
}

fn json_artifact(path: &str, value: Value) -> Result<GeneratedArtifact, ContractGenerationError> {
    let mut bytes = serde_json::to_vec_pretty(&value)?;
    bytes.push(b'\n');
    Ok(GeneratedArtifact {
        path: path.into(),
        bytes,
    })
}

fn compact_json_artifact(
    path: &str,
    value: Value,
) -> Result<GeneratedArtifact, ContractGenerationError> {
    let mut bytes = serde_json::to_vec(&value)?;
    bytes.push(b'\n');
    Ok(GeneratedArtifact {
        path: path.into(),
        bytes,
    })
}

fn rust_schema<T: JsonSchema>() -> Value {
    let schema = SchemaSettings::draft2020_12()
        .into_generator()
        .into_root_schema_for::<T>();
    serde_json::to_value(schema).expect("Schemars schemas always serialize")
}

fn root_schema<T: JsonSchema>(id: &str, title: &str) -> Value {
    let mut schema = rust_schema::<T>();
    strip_optional_nulls(&mut schema);
    let root = object_mut(&mut schema);
    root.insert("$id".into(), id.into());
    root.insert("title".into(), title.into());
    root.insert("x-contract-owner".into(), CONTRACT_OWNER.into());
    schema
}

// Schema major 1 globally represents an absent optional value by omitting it.
// MCP `ttl` is the sole nullable field and is required, so it is not rewritten.
fn strip_optional_nulls(schema: &mut Value) {
    if let Some(object) = schema.as_object_mut() {
        let required: Vec<_> = object
            .get("required")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .map(str::to_owned)
            .collect();
        if let Some(properties) = object.get_mut("properties").and_then(Value::as_object_mut) {
            for (name, property) in properties {
                if !required.iter().any(|required| required == name) {
                    remove_null_variant(property);
                }
            }
        }
        for value in object.values_mut() {
            strip_optional_nulls(value);
        }
    } else if let Some(array) = schema.as_array_mut() {
        for value in array {
            strip_optional_nulls(value);
        }
    }
}

fn remove_null_variant(schema: &mut Value) {
    if let Some(types) = schema.get_mut("type").and_then(Value::as_array_mut) {
        types.retain(|kind| kind != "null");
    }
    for keyword in ["anyOf", "oneOf"] {
        if let Some(variants) = schema.get_mut(keyword).and_then(Value::as_array_mut) {
            variants.retain(|variant| variant.get("type") != Some(&json!("null")));
        }
    }
}

fn object_mut(value: &mut Value) -> &mut Map<String, Value> {
    value
        .as_object_mut()
        .expect("contract schemas are JSON objects")
}

fn property_mut<'a>(schema: &'a mut Value, property: &str) -> &'a mut Map<String, Value> {
    schema["properties"][property]
        .as_object_mut()
        .expect("derived property schema is an object")
}

fn set_const(schema: &mut Value, property: &str, value: Value) {
    let property = property_mut(schema, property);
    property.clear();
    property.insert("const".into(), value);
}

fn set_pattern(schema: &mut Value, property: &str, pattern: &str) {
    property_mut(schema, property).insert("pattern".into(), pattern.into());
}

fn config_schema() -> Value {
    let mut schema = root_schema::<schema_types::Config>(
        "https://pangram.micr.dev/schemas/config-v1.json",
        "Pangram CLI configuration v1",
    );
    set_const(&mut schema, "config_version", json!(1));
    schema["$defs"]["HistoryConfig"]["properties"]["enabled"]["default"] = json!(false);
    schema["$defs"]["TuiConfig"]["properties"]["intro"]["default"] = json!("once");
    schema["$defs"]["TuiConfig"]["properties"]["keymap"]["default"] = json!("regular");
    schema["$defs"]["TuiConfig"]["properties"]["motion"]["default"] = json!("full");
    let rate = &mut schema["$defs"]["NetworkConfig"]["properties"]["max_requests_per_second"];
    object_mut(rate).remove("minimum");
    object_mut(rate).insert("exclusiveMinimum".into(), json!(0));
    object_mut(rate).insert("default".into(), json!(5));
    schema
}

