fn cli_reference() -> Value {
    let mut value =
        serde_json::to_value(FULL_GRAMMAR).expect("the static CLI grammar always serializes");
    let root = object_mut(&mut value);
    root.insert("$schema".into(), DRAFT_2020_12.into());
    root.insert(
        "$id".into(),
        "https://pangram.micr.dev/generated/cli-reference-v1.json".into(),
    );
    root.insert("title".into(), "Pangram CLI grammar reference v1".into());
    root.insert("x-contract-owner".into(), CONTRACT_OWNER.into());
    value
}

fn error_reference() -> Value {
    let errors: Vec<_> = ErrorCode::ALL
        .iter()
        .map(|code| {
            json!({
                "code": code.as_str(),
                "category": code.category().as_str(),
                "default_retryable": code.default_retryable(),
                "contextual_retryability": code.retryability_is_contextual(),
            })
        })
        .collect();
    let exits: Vec<_> = ExitCode::ALL
        .iter()
        .map(|code| json!({"code": code.as_u8()}))
        .collect();
    json!({
        "$schema": DRAFT_2020_12,
        "$id": "https://pangram.micr.dev/generated/error-reference-v1.json",
        "x-contract-owner": CONTRACT_OWNER,
        "title": "Pangram CLI error and exit-code reference v1",
        "schema_version": "1",
        "errors": errors,
        "exit_codes": exits,
    })
}

// The output schema combines Schemars-owned definitions with cross-field JSON
// Schema constraints which Rust's type system cannot express by derivation.
fn output_schema() -> Value {
    let mut registry = rust_schema::<schema_types::OutputRegistry>();
    strip_optional_nulls(&mut registry);
    let mut definitions = object_mut(&mut registry)
        .remove("$defs")
        .expect("the output registry has definitions");

    patch_output_definitions(&mut definitions);
    let analysis = schema_ref::<Analysis<CanonicalError>>();
    let array = json!({"type": "array", "minItems": 1, "items": analysis});
    let conditions = vec![
        data_condition(
            &["detect", "plagiarism", "analyze"],
            json!({"oneOf": [analysis, array]}),
        ),
        data_condition(
            &["task_status", "task_wait", "history_show", "history_rerun"],
            schema_ref::<Analysis<CanonicalError>>(),
        ),
        data_condition(
            &["bulk_submit", "bulk_status", "bulk_wait"],
            schema_ref::<BulkCollection>(),
        ),
        data_condition(&["bulk_results"], schema_ref::<BulkPage<CanonicalError>>()),
        data_condition(
            &["history_list", "history_search"],
            schema_ref::<AnalysisPage<CanonicalError>>(),
        ),
        data_condition(
            &[
                "history_delete",
                "history_clear",
                "auth_set",
                "auth_logout",
                "config_set",
                "mcp_install",
                "mcp_uninstall",
            ],
            schema_ref::<crate::output::MutationAcknowledgement>(),
        ),
        data_condition(&["auth_status"], schema_ref::<crate::output::AuthStatus>()),
        data_condition(
            &["config_list"],
            schema_ref::<crate::output::ConfigListStatus>(),
        ),
        data_condition(
            &["config_get"],
            schema_ref::<crate::output::ConfigGetStatus>(),
        ),
        data_condition(
            &["config_path"],
            schema_ref::<crate::output::ConfigPathStatus>(),
        ),
        data_condition(&["doctor"], schema_ref::<crate::output::DoctorStatus>()),
        data_condition(&["mcp_status"], schema_ref::<crate::output::McpStatus>()),
        data_condition(
            &["update_check", "update_install"],
            schema_ref::<crate::output::UpdateStatus>(),
        ),
    ];
    let json_commands: Vec<_> = ResolvedCommand::ALL
        .iter()
        .copied()
        .filter(|command| command.uses_json_envelope())
        .map(ResolvedCommand::as_str)
        .collect();
    let all_commands: Vec<_> = ResolvedCommand::ALL
        .iter()
        .copied()
        .map(ResolvedCommand::as_str)
        .collect();

    let definitions = object_mut(&mut definitions);
    definitions.insert(
        "successEnvelope".into(),
        json!({
            "type": "object",
            "required": ["schema_version", "command", "data", "meta"],
            "properties": {
                "schema_version": {"const": "1"},
                "command": {"enum": json_commands},
                "data": {"oneOf": [{"type": "object"}, {"type": "array"}]},
                "meta": schema_ref::<EnvelopeMeta>(),
            },
            "allOf": conditions,
            "not": {"required": ["error"]},
            "additionalProperties": true,
        }),
    );
    definitions.insert(
        "errorEnvelope".into(),
        json!({
            "type": "object",
            "required": ["schema_version", "command", "error", "meta"],
            "properties": {
                "schema_version": {"const": "1"},
                "command": {"enum": all_commands},
                "error": schema_ref::<CanonicalError>(),
                "meta": schema_ref::<EnvelopeMeta>(),
            },
            "not": {"required": ["data"]},
            "additionalProperties": true,
        }),
    );

    json!({
        "$schema": DRAFT_2020_12,
        "$id": "https://pangram.micr.dev/schemas/output-v1.json",
        "x-contract-owner": CONTRACT_OWNER,
        "title": "Pangram CLI output envelope v1",
        "oneOf": [
            {"$ref": "#/$defs/successEnvelope"},
            {"$ref": "#/$defs/errorEnvelope"}
        ],
        "$defs": definitions,
    })
}

fn schema_ref<T: JsonSchema>() -> Value {
    json!({"$ref": format!("#/$defs/{}", T::schema_name())})
}

fn data_condition(commands: &[&str], data: Value) -> Value {
    let command = if commands.len() == 1 {
        json!({"const": commands[0]})
    } else {
        json!({"enum": commands})
    };
    json!({
        "if": {"properties": {"command": command}, "required": ["command"]},
        "then": {"properties": {"data": data}},
    })
}

fn definition_mut<T: JsonSchema>(definitions: &mut Value) -> &mut Value {
    &mut definitions[T::schema_name().as_ref()]
}

fn patch_output_definitions(definitions: &mut Value) {
    if let Some(timestamp) = definitions.get_mut("Timestamp") {
        object_mut(timestamp).insert("pattern".into(), "Z$".into());
    }

    // Internally tagged Serde enums ignore known fields from other variants.
    // Keep the schema strict even though those variants share open objects.
    let check_state_invariant = json!({"oneOf": state_payload_invariant("result")});
    for (name, definition) in object_mut(definitions).iter_mut() {
        if name.starts_with("CheckState") {
            object_mut(definition).insert("allOf".into(), json!([check_state_invariant]));
        }
    }

    let checks = definition_mut::<OrderedChecks<Check<CanonicalError>>>(definitions);
    object_mut(checks).insert(
        "allOf".into(),
        json!([{
            "if": {"minItems": 2},
            "then": {
                "prefixItems": [
                    {"properties": {"kind": {"const": "ai_detection"}}, "required": ["kind"]},
                    {"properties": {"kind": {"const": "plagiarism"}}, "required": ["kind"]}
                ]
            }
        }]),
    );
    let analysis = definition_mut::<Analysis<CanonicalError>>(definitions);
    object_mut(analysis).insert("not".into(), json!({"required": ["retry_of", "rerun_of"]}));
    push_all_of(
        analysis,
        when_not_submitted(json!({
            "properties": {
                "checks": {
                    "not": {
                        "contains": {
                            "properties": {
                                "upstream": {
                                    "type": "object",
                                    "required": ["task_id"]
                                }
                            },
                            "required": ["upstream"]
                        }
                    }
                },
                "provenance": {
                    "not": {
                        "anyOf": [
                            {"required": ["upstream_task_ids"]},
                            {"required": ["upstream_bulk_id"]},
                            {"required": ["submitted_at"]},
                            {"required": ["completed_at"]}
                        ]
                    }
                }
            }
        })),
    );
    push_all_of(
        definition_mut::<BulkCollection>(definitions),
        when_not_submitted(json!({
            "properties": {
                "accepted": {"const": 0},
                "succeeded": {"const": 0},
                "failed": {"const": 0}
            },
            "not": {"required": ["upstream_bulk_id"]}
        })),
    );
    let bulk_item = definition_mut::<BulkItem<CanonicalError>>(definitions);
    let properties = object_mut(&mut bulk_item["properties"]);
    let mut status = rust_schema::<CheckStatus>();
    object_mut(&mut status).remove("$schema");
    object_mut(&mut status).remove("title");
    properties.insert("status".into(), status);
    properties.insert("analysis".into(), schema_ref::<Analysis<CanonicalError>>());
    properties.insert("error".into(), schema_ref::<CanonicalError>());
    bulk_item["required"]
        .as_array_mut()
        .expect("BulkItem required fields are an array")
        .push(json!("status"));
    object_mut(bulk_item).insert("oneOf".into(), state_payload_invariant("analysis"));

    let unknown_submission = definition_mut::<SubmissionOutcomeUnknownDetails>(definitions);
    let properties = object_mut(&mut unknown_submission["properties"]);
    properties.insert(
        "analysis_id".into(),
        schema_ref::<crate::domain::AnalysisId>(),
    );
    properties.insert("bulk_id".into(), schema_ref::<crate::domain::BulkId>());
    object_mut(unknown_submission).insert("additionalProperties".into(), json!(false));

    let error = definition_mut::<CanonicalError>(definitions);
    property_mut(error, "message").insert("minLength".into(), json!(1));
    object_mut(error).insert(
        "allOf".into(),
        json!([
            error_category_invariant(),
            error_retry_invariant(),
            {
                "if": {"properties": {"code": {"const": "submission_outcome_unknown"}}},
                "then": {
                    "properties": {
                        "retryable": {"const": false},
                        "details": schema_ref::<SubmissionOutcomeUnknownDetails>(),
                        "recovery": {
                            "type": "object",
                            "properties": {
                                "message": {
                                    "const": SUBMISSION_OUTCOME_UNKNOWN_RECOVERY_MESSAGE
                                }
                            },
                            "required": ["message"],
                            "additionalProperties": false
                        }
                    },
                    "required": ["details", "recovery"]
                }
            }
        ]),
    );
}

fn push_all_of(schema: &mut Value, invariant: Value) {
    object_mut(schema)
        .entry("allOf")
        .or_insert_with(|| json!([]))
        .as_array_mut()
        .expect("allOf is an array")
        .push(invariant);
}

fn when_not_submitted(then: Value) -> Value {
    json!({
        "if": {
            "properties": {"submission_outcome": {"const": "not_submitted"}},
            "required": ["submission_outcome"]
        },
        "then": then
    })
}

fn state_payload_invariant(success_field: &str) -> Value {
    json!([
        {
            "properties": {"status": {"enum": ["queued", "running"]}},
            "not": {"anyOf": [{"required": [success_field]}, {"required": ["error"]}]}
        },
        {
            "properties": {"status": {"const": "succeeded"}},
            "required": [success_field],
            "not": {"required": ["error"]}
        },
        {
            "properties": {"status": {"const": "failed"}},
            "required": ["error"],
            "not": {"required": [success_field]}
        }
    ])
}

fn error_category_invariant() -> Value {
    let mut categories: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for code in ErrorCode::ALL {
        categories
            .entry(code.category().as_str())
            .or_default()
            .push(code.as_str());
    }
    let variants: Vec<_> = categories
        .into_iter()
        .map(|(category, codes)| {
            json!({
                "properties": {
                    "code": {"enum": codes},
                    "category": {"const": category}
                }
            })
        })
        .collect();
    json!({"oneOf": variants})
}

fn error_retry_invariant() -> Value {
    let retryable: Vec<_> = ErrorCode::ALL
        .iter()
        .filter(|code| code.default_retryable())
        .map(|code| code.as_str())
        .collect();
    let fixed_non_retryable: Vec<_> = ErrorCode::ALL
        .iter()
        .filter(|code| !code.default_retryable() && !code.retryability_is_contextual())
        .map(|code| code.as_str())
        .collect();
    json!({
        "allOf": [
            {
                "if": {"properties": {"code": {"enum": retryable}}},
                "then": {"properties": {"retryable": {"const": true}}}
            },
            {
                "if": {"properties": {"code": {"enum": fixed_non_retryable}}},
                "then": {"properties": {"retryable": {"const": false}}}
            }
        ]
    })
}
